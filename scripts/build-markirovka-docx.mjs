// Запуск: node scripts/build-markirovka-docx.mjs
import {
  Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell,
  WidthType, ShadingType, AlignmentType, BorderStyle, PageOrientation, LevelFormat,
} from 'docx'
import { writeFileSync } from 'node:fs'

const GREY = 'F2F2F2'
const p = (text, o = {}) => new Paragraph({ spacing: { after: 140 }, ...o, children: [new TextRun({ text, ...o.run })] })
const h = (text, level) => new Paragraph({ heading: level, spacing: { before: 320, after: 160 }, children: [new TextRun(text)] })

/** Ячейка таблицы: w — ширина в DXA, head — шапка (жирная, с заливкой) */
const cell = (text, w, head = false) =>
  new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: head ? { type: ShadingType.CLEAR, fill: GREY, color: 'auto' } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ children: [new TextRun({ text, bold: head, size: 20 })] })],
  })

const table = (widths, rows) =>
  new Table({
    columnWidths: widths,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows: rows.map((cells, i) => new TableRow({
      tableHeader: i === 0,
      children: cells.map((t, j) => cell(t, widths[j], i === 0)),
    })),
  })

